"""Persistence and mount boundaries for application-owned S3 drives."""

from typing import Protocol

from aws_connect.application.operations import OperationContext
from aws_connect.domain.aws_profile import PlainCredentials
from aws_connect.domain.s3_drive import DriveStatus, S3Drive


class S3DriveStore(Protocol):
    def list_drives(self, profile_id: int | None = None) -> list[S3Drive]: ...
    def get_drive(self, drive_id: int) -> S3Drive | None: ...
    def save_drive(self, drive: S3Drive) -> S3Drive: ...
    def delete_drive(self, drive_id: int) -> None: ...


class S3DriveMount(Protocol):
    def available_letters(self) -> set[str]: ...
    def status(self, drive: S3Drive) -> DriveStatus: ...
    def connect(
        self, drive: S3Drive, credentials: PlainCredentials, region: str, context: OperationContext
    ) -> None: ...
    def disconnect(self, drive: S3Drive) -> None: ...
    def assert_editable(self, drive: S3Drive) -> None: ...
